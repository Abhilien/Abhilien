let seedIndex = 0;

function person(spec: Spec, now: number): User {
  const iso = (daysAgo: number) => new Date(now - daysAgo * DAY).toISOString();
  const verification = Object.fromEntries(
    (['identity', 'phone', 'photo', 'employment', 'education', 'profile'] as VerificationKey[]).map((k) => [
      k,
      (spec.verified ?? ['phone']).includes(k),
    ]),
  ) as Record<VerificationKey, boolean>;
  return {
    id: spec.id,
    plan: spec.plan ?? 'free',
    verification,
    persona: spec.persona ? { tagline: spec.persona } : undefined,
    profile: {
      firstName: spec.name,
      age: spec.age,
      gender: spec.gender,
      seeking: spec.seeking ?? (spec.gender === 'man' ? ['woman'] : spec.gender === 'woman' ? ['man'] : ['woman', 'man', 'nonbinary']),
      place: spec.place,
      profession: spec.profession,
      education: spec.education,
      bio: spec.bio,
      intent: spec.intent,
      intentNext: spec.intentNext,
      lifestyle: spec.lifestyle,
      interests: spec.interests,
      values: spec.values,
      languages: spec.languages,
      future: spec.future ?? {},
      prompt: spec.prompt,
      portraits: portraits(seedIndex++, spec.gender),
      openTo: spec.openTo ?? (spec.intent === 'friendship' ? ['friendship'] : ['romantic']),
    },
    settings: { ...defaultSettings, ...spec.settings },
    history: {
      memberSince: iso(spec.since),
      meaningfulInteractions: 0,
      mutualConnections: 0,
      completedConversations: 0,
      meetings: 0,
      movedToFriendship: 0,
      durations: [],
      beyondInitialPct: 0,
      toMeetingPct: 0,
      changes: {},
      ...spec.history,
    },
  };
}

