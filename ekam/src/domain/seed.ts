function portraits(seed: number, gender: Gender): Portrait[] {
  const base: Portrait['variant'][] = gender === 'man' ? [2, 3] : gender === 'woman' ? [0, 1] : [1, 2];
  return [0, 1, 2].map((i) => {
    const [from, to, ink] = TONES[(seed + i * 3) % TONES.length];
    return { from, to, ink, variant: base[(seed + i) % 2] };
  });
}

