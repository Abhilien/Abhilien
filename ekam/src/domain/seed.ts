function conn(
  id: string,
  a: string,
  b: string,
  kind: Kind,
  status: Connection['status'],
  mutualDaysAgo: number,
  now: number,
  extra: Partial<Connection> = {},
): Connection {
  return {
    id,
    users: [a, b],
    kind,
    status,
    mutualAt: new Date(now - mutualDaysAgo * DAY).toISOString(),
    stagesReached: [],
    messages: [],
    meetingReady: {},
    checkins: {},
    feedbackDue: [],
    ...extra,
  };
}

function thread(now: number, startDaysAgo: number, lines: [string, string][]): Message[] {
  const start = now - startDaysAgo * DAY;
  const step = (startDaysAgo * DAY) / (lines.length + 1);
  return lines.map(([from, text], i) => ({
    id: `m_seed_${startDaysAgo}_${i}`,
    from,
    text,
    at: new Date(start + step * (i + 1)).toISOString(),
    kind: from === 'system' ? 'system' : 'text',
  }));
}

