function generateFeedback(
  about: string,
  n: number,
  rates: Partial<Record<Trait, number>>,
  now: number,
): FeedbackEntry[] {
  const comments = POSITIVE_COMMENTS[about] ?? [];
  return Array.from({ length: n }, (_, i) => {
    const traits = Object.fromEntries(
      TRAITS.map((t) => [t, i < Math.round((rates[t] ?? 0.92) * n)]),
    ) as Record<Trait, boolean>;
    return {
      id: `f_${about}_${i}`,
      about,
      author: `former_${about}_${i}`,
      traits,
      comment: comments[i],
      at: new Date(now - (20 + i * 23) * DAY).toISOString(),
      status: 'published' as const,
    };
  });
}

